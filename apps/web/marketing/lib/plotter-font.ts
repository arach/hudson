export function strokeLengthOfPolyline(pts: GlyphPoint[]): number {
  let L = 0;
  for (let i = 1; i < pts.length; i++) {
    const dx = pts[i][0] - pts[i - 1][0];
    const dy = pts[i][1] - pts[i - 1][1];
    L += Math.hypot(dx, dy);
  }
  return L;
}
