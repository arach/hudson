import Foundation

/// Stable upstream model identifier. Unknown IDs remain unknown and round-trip.
public struct HudTranscriptionModelID: RawRepresentable, Codable, Hashable, Sendable, ExpressibleByStringLiteral {
    public var rawValue: String

    public init(rawValue: String) {
        self.rawValue = rawValue
    }

    public init(stringLiteral value: String) {
        self.rawValue = value
    }
}
